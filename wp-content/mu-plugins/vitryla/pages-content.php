/**
 * Заповнює сторінки, проставляє ліди й порядок у меню.
 */
function vitryla_seed_pages(): void {
	if ( (int) get_option( 'vitryla_pages_version' ) >= VITRYLA_PAGES_VERSION ) {
		return;
	}
	if ( ! function_exists( 'vitryla_page_by_slug' ) ) {
		return;
	}

	// Порядок сторінок усередині розділів — як у задуманій структурі.
	if ( function_exists( 'vitryla_tree' ) ) {
		$order = 0;
		foreach ( vitryla_tree() as $sec => [ $title, $children ] ) {
			$sp = vitryla_page_by_slug( $sec );
			if ( $sp ) {
				wp_update_post( array( 'ID' => $sp->ID, 'menu_order' => $order++ ) );
			}
			$i = 0;
			foreach ( array_keys( $children ) as $slug ) {
				$cp = vitryla_page_by_slug( $slug );
				if ( $cp ) {
					wp_update_post( array( 'ID' => $cp->ID, 'menu_order' => $i++ ) );
				}
			}
		}
	}

	foreach ( vitryla_page_bodies() as $slug => $cfg ) {
		$page = vitryla_page_by_slug( $slug );
		if ( ! $page ) {
			continue;
		}

		$upd = array( 'ID' => $page->ID, 'post_excerpt' => $cfg['lead'] );

		$is_placeholder = str_contains( $page->post_content, 'vit-brief' ) || '' === trim( wp_strip_all_tags( $page->post_content ) );
		if ( ! empty( $cfg['body'] ) && $is_placeholder ) {
			$upd['post_content'] = $cfg['body'];
			update_post_meta( $page->ID, 'vit_template', 1 );
		}
		wp_update_post( $upd );
	}

	vitryla_seed_more_demo();

	update_option( 'vitryla_pages_version', VITRYLA_PAGES_VERSION );
}

/**
 * Пошук запису за точною назвою (get_page_by_title застарів у WP 6.2).
 */
function vitryla_post_by_title( string $title, string $pt ): bool {
	return (bool) get_posts( array(
		'post_type'      => $pt,
		'title'          => $title,
		'post_status'    => 'any',
		'posts_per_page' => 1,
		'fields'         => 'ids',
	) );
}

