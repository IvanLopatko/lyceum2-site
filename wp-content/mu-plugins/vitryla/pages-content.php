/* ═════════ Будівельні блоки ═════════ */

function vb_p( string $t, string $cls = '' ): string {
	if ( $cls ) {
		return "<!-- wp:paragraph {\"className\":\"$cls\"} -->\n<p class=\"$cls\">$t</p>\n<!-- /wp:paragraph -->\n\n";
	}
	return "<!-- wp:paragraph -->\n<p>$t</p>\n<!-- /wp:paragraph -->\n\n";
}

function vb_h( string $t, int $l = 2, string $cls = '' ): string {
	$attrs = array();
	if ( 2 !== $l ) {
		$attrs['level'] = $l;
	}
	if ( $cls ) {
		$attrs['className'] = $cls;
	}
	$a = $attrs ? ' ' . wp_json_encode( $attrs ) : '';
	$c = 'wp-block-heading' . ( $cls ? " $cls" : '' );
	return "<!-- wp:heading$a -->\n<h$l class=\"$c\">$t</h$l>\n<!-- /wp:heading -->\n\n";
}

function vb_list( array $items, string $cls = '', bool $ordered = false ): string {
	$attrs = array();
	if ( $ordered ) {
		$attrs['ordered'] = true;
	}
	if ( $cls ) {
		$attrs['className'] = $cls;
	}
	$a   = $attrs ? ' ' . wp_json_encode( $attrs ) : '';
	$tag = $ordered ? 'ol' : 'ul';
	$out = "<!-- wp:list$a -->\n<$tag class=\"wp-block-list" . ( $cls ? " $cls" : '' ) . '">';
	foreach ( $items as $i ) {
		$out .= "<!-- wp:list-item -->\n<li>$i</li>\n<!-- /wp:list-item -->";
	}
	return $out . "</$tag>\n<!-- /wp:list -->\n\n";
}

function vb_steps( array $items ): string {
	return vb_list( $items, 'vit-steps', true );
}

function vb_timeline( array $items ): string {
	return vb_list( array_map( fn( $i ) => "<strong>{$i[0]}</strong>{$i[1]}", $items ), 'vit-timeline' );
}

function vb_cards( array $cards, string $min = '15rem' ): string {
	$tones = array( 'blue', 'sun', 'green', 'sail' );
	$out   = "<!-- wp:group {\"className\":\"vit-cards\",\"layout\":{\"type\":\"grid\",\"minimumColumnWidth\":\"$min\"}} -->\n<div class=\"wp-block-group vit-cards\">";
	foreach ( array_values( $cards ) as $i => $c ) {
		$icon = $c[0];
		$tone = $c[3] ?? $tones[ $i % 4 ];
		$out .= "<!-- wp:group {\"className\":\"vit-card-item is-$tone vit-glow\",\"layout\":{\"type\":\"default\"}} -->\n<div class=\"wp-block-group vit-card-item is-$tone vit-glow\">"
			. vb_h( $c[1], 3, "vit-i-$icon" ) . vb_p( $c[2] )
			. "</div>\n<!-- /wp:group -->\n";
	}
	return $out . "</div>\n<!-- /wp:group -->\n\n";
}

function vb_stats( array $items, string $min = '11rem' ): string {
	$tones = array( 'blue', 'sun', 'green', 'sail' );
	$out   = "<!-- wp:group {\"className\":\"vit-stats\",\"layout\":{\"type\":\"grid\",\"minimumColumnWidth\":\"$min\"}} -->\n<div class=\"wp-block-group vit-stats\">";
	foreach ( array_values( $items ) as $i => $s ) {
		$tone = $tones[ $i % 4 ];
		$out .= "<!-- wp:group {\"className\":\"vit-stat is-$tone\",\"layout\":{\"type\":\"default\"}} -->\n<div class=\"wp-block-group vit-stat is-$tone\">"
			. vb_p( $s[0], 'vit-stat-n' ) . vb_p( $s[1], 'vit-stat-l' ) . ( ! empty( $s[2] ) ? vb_p( $s[2], 'vit-stat-note' ) : '' )
			. "</div>\n<!-- /wp:group -->\n";
	}
	return $out . "</div>\n<!-- /wp:group -->\n\n";
}

function vb_faq( array $items ): string {
	$out = "<!-- wp:group {\"className\":\"vit-faq\",\"layout\":{\"type\":\"default\"}} -->\n<div class=\"wp-block-group vit-faq\">";
	foreach ( $items as [ $q, $a ] ) {
		$out .= "<!-- wp:details -->\n<details class=\"wp-block-details\"><summary>$q</summary>"
			. "<!-- wp:paragraph -->\n<p>$a</p>\n<!-- /wp:paragraph --></details>\n<!-- /wp:details -->\n";
	}
	return $out . "</div>\n<!-- /wp:group -->\n\n";
}

function vb_table( array $head, array $rows ): string {
	$h = '<tr>' . implode( '', array_map( fn( $c ) => "<th>$c</th>", $head ) ) . '</tr>';
	$b = '';
	foreach ( $rows as $r ) {
		$b .= '<tr>' . implode( '', array_map( fn( $c ) => "<td>$c</td>", $r ) ) . '</tr>';
	}
	return "<!-- wp:table {\"className\":\"vit-table\"} -->\n<figure class=\"wp-block-table vit-table\"><table class=\"has-fixed-layout\"><thead>$h</thead><tbody>$b</tbody></table></figure>\n<!-- /wp:table -->\n\n";
}

function vb_callout( string $text, string $tone = 'sun', string $title = '' ): string {
	return "<!-- wp:group {\"className\":\"vit-callout is-$tone\",\"layout\":{\"type\":\"default\"}} -->\n<div class=\"wp-block-group vit-callout is-$tone\">"
		. ( $title ? vb_h( $title, 3 ) : '' ) . vb_p( $text )
		. "</div>\n<!-- /wp:group -->\n\n";
}

function vb_sc( string $code ): string {
	return "<!-- wp:shortcode -->\n$code\n<!-- /wp:shortcode -->\n\n";
}

function vb_buttons( array $btns ): string {
	$out = "<!-- wp:buttons -->\n<div class=\"wp-block-buttons\">";
	foreach ( $btns as $i => [ $label, $url ] ) {
		if ( 0 === $i ) {
			$out .= "<!-- wp:button -->\n<div class=\"wp-block-button\"><a class=\"wp-block-button__link wp-element-button\" href=\"$url\">$label</a></div>\n<!-- /wp:button -->";
		} else {
			$out .= "<!-- wp:button {\"className\":\"is-style-outline\"} -->\n<div class=\"wp-block-button is-style-outline\"><a class=\"wp-block-button__link wp-element-button\" href=\"$url\">$label</a></div>\n<!-- /wp:button -->";
		}
	}
	return $out . "</div>\n<!-- /wp:buttons -->\n\n";
}

function vb_html( string $raw ): string {
	return "<!-- wp:html -->\n$raw\n<!-- /wp:html -->\n\n";
}

