const VITRYLA_CONTENT_VERSION = 2;

add_action( 'admin_init', 'vitryla_fill_static_pages', 20 );

/**
 * Записує готові тексти у відповідні сторінки.
 */
function vitryla_fill_static_pages(): void {
	if ( (int) get_option( 'vitryla_content_version' ) >= VITRYLA_CONTENT_VERSION ) {
		return;
	}

	foreach ( vitryla_static_content() as $slug => $body ) {
		$page = vitryla_page_by_slug( $slug );
		if ( ! $page ) {
			continue;
		}
		wp_update_post( array(
			'ID'           => $page->ID,
			'post_content' => trim( $body ),
		) );
	}

	update_option( 'vitryla_content_version', VITRYLA_CONTENT_VERSION );
}

/**
 * Пошук сторінки за слагом незалежно від рівня вкладеності.
 * get_page_by_path() для дочірніх сторінок вимагає повний шлях,
 * тому для них не годиться.
 */
function vitryla_page_by_slug( string $slug ): ?WP_Post {
	$found = get_posts( array(
		'post_type'      => 'page',
		'name'           => $slug,
		'posts_per_page' => 1,
		'post_status'    => 'any',
	) );
	return $found ? $found[0] : null;
}

